drop policy if exists adm_self on public.admins;
create policy cat_read on public.categories for select to anon, authenticated using (true);
create policy cat_admin on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy menu_read on public.menu_items for select to anon, authenticated using (available or public.is_admin());
create policy menu_admin on public.menu_items for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy tbl_admin on public.restaurant_tables for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy ord_admin on public.orders for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy oi_admin on public.order_items for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy adm_self on public.admins for select to authenticated using (user_id=auth.uid());

create or replace function public.get_table(tok text)
returns integer language sql stable security definer
set search_path = pg_catalog, public
as $$ select number from public.restaurant_tables where token=tok and active limit 1 $$;

create or replace function public.create_order(p jsonb)
returns bigint language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare
  v_type text := p->>'type';
  v_table_id bigint;
  v_order_id bigint;
  v_total bigint := 0;
  v_item record;
  v_line jsonb;
  v_qty integer;
  v_idem uuid;
  v_items jsonb := p->'items';
begin
  if auth.role() not in ('anon','authenticated') then raise exception 'unauthorized'; end if;
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'invalid_payload'; end if;
  if v_type not in ('dinein','delivery','pickup') then raise exception 'invalid_order_type'; end if;
  begin v_idem := (p->>'idem')::uuid; exception when others then raise exception 'invalid_idempotency_key'; end;
  -- Serialize duplicate submissions with the same key before checking/inserting.
  perform pg_advisory_xact_lock(hashtextextended(v_idem::text, 0));
  select id into v_order_id from public.orders where idem=v_idem;
  if found then return v_order_id; end if;

  if v_type='dinein' then
    select id into v_table_id from public.restaurant_tables
      where token=left(coalesce(p->>'table',''),100) and active;
    if v_table_id is null then raise exception 'invalid_or_inactive_table'; end if;
  else
    if length(trim(coalesce(p->>'name',''))) < 2 or length(regexp_replace(coalesce(p->>'phone',''),'\D','','g')) < 7 then
      raise exception 'invalid_customer_contact';
    end if;
    if v_type='delivery' and length(trim(coalesce(p->>'address',''))) < 5 then raise exception 'invalid_delivery_address'; end if;
  end if;
  if jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) not between 1 and 40 then raise exception 'invalid_order_items'; end if;

  insert into public.orders(type,table_id,customer_name,phone,address,note,total,idem)
  values(v_type,v_table_id,left(trim(coalesce(p->>'name','')),80),left(trim(coalesce(p->>'phone','')),30),
    left(trim(coalesce(p->>'address','')),300),left(trim(coalesce(p->>'note','')),500),0,v_idem)
  returning id into v_order_id;

  for v_line in select value from jsonb_array_elements(v_items) loop
    begin v_qty := (v_line->>'qty')::integer; exception when others then raise exception 'invalid_quantity'; end;
    if v_qty not between 1 and 50 then raise exception 'invalid_quantity'; end if;
    select id,name,price into v_item from public.menu_items
      where id=(v_line->>'id')::bigint and available for share;
    if not found then raise exception 'menu_item_unavailable'; end if;
    insert into public.order_items(order_id,item_id,name,price,qty,note)
    values(v_order_id,v_item.id,v_item.name,v_item.price,v_qty,left(trim(coalesce(v_line->>'note','')),200));
    v_total := v_total + (v_item.price::bigint * v_qty);
    if v_total > 2147483647 then raise exception 'order_total_too_large'; end if;
  end loop;
  update public.orders set total=v_total::integer where id=v_order_id;
  return v_order_id;
end $$;


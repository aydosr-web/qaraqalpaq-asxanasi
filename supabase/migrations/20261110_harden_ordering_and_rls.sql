-- Apply as a database owner after taking a backup. This idempotent migration refreshes policies/functions and preserves existing rows.
-- QARAQALPAQ ASXANASI restaurant database
-- Run in Supabase SQL Editor for a new project. Existing deployments should use migrations.
create extension if not exists pgcrypto;

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 80),
  sort integer not null default 0
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name text not null check (length(trim(name)) between 1 and 120),
  description text not null default '',
  price integer not null check (price >= 0),
  image_url text,
  available boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.restaurant_tables (
  id bigint generated by default as identity primary key,
  number integer unique not null check (number > 0),
  token text unique not null default encode(gen_random_bytes(18),'hex'),
  active boolean not null default true
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('dinein','delivery','pickup')),
  table_id bigint references public.restaurant_tables(id),
  customer_name text,
  phone text,
  address text,
  note text,
  status text not null default 'new' check (status in ('new','accepted','preparing','ready','completed','cancelled')),
  total integer not null default 0 check (total >= 0),
  idem uuid unique not null,
  created_at timestamptz not null default now(),
  constraint order_contact_check check (
    (type='dinein') or
    (length(coalesce(customer_name,'')) >= 2 and length(coalesce(phone,'')) >= 7)
  ),
  constraint order_delivery_address_check check (type <> 'delivery' or length(coalesce(address,'')) >= 5),
  constraint order_table_check check ((type='dinein' and table_id is not null) or (type<>'dinein' and table_id is null))
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  item_id bigint references public.menu_items(id) on delete set null,
  name text not null,
  price integer not null check (price >= 0),
  qty integer not null check (qty between 1 and 50),
  note text
);

create index if not exists menu_items_category_idx on public.menu_items(category_id);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists order_items_order_idx on public.order_items(order_id);

create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path = pg_catalog, public
as $$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

alter table public.admins enable row level security;
alter table public.categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.restaurant_tables enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists cat_read on public.categories;
drop policy if exists cat_admin on public.categories;
drop policy if exists menu_read on public.menu_items;
drop policy if exists menu_admin on public.menu_items;
drop policy if exists tbl_admin on public.restaurant_tables;
drop policy if exists ord_admin on public.orders;
